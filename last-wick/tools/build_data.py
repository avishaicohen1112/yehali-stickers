"""Generate js/data.js: world rooms + atlas metas + room art manifest."""
import json, os, glob
import world
ROOT = os.path.join(os.path.dirname(__file__), '..')
d = world.export()
atlases = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'assets/sprites/*.json'))):
    atlases[os.path.basename(f)[:-5]] = json.load(open(f))
art = {}
p = os.path.join(ROOT, 'assets/rooms/manifest.json')
if os.path.exists(p): art = json.load(open(p))
props = {}
p = os.path.join(ROOT, 'assets/props/manifest.json')
if os.path.exists(p): props = json.load(open(p))
bgs = {}
p = os.path.join(ROOT, 'assets/bg/manifest.json')
if os.path.exists(p): bgs = json.load(open(p))
scenes = {}
p = os.path.join(ROOT, 'assets/scenes.json')
if os.path.exists(p): scenes = json.load(open(p))
# default scenes from the old 3D-rendered layers, so the scenery engine is always used
FOG = {'crypts': [255, 170, 110], 'gardens': [120, 255, 210], 'nave': [130, 170, 255], 'spire': [210, 180, 255], 'hearth': [255, 110, 60]}
SKY = {'crypts': ['#120c10', '#2a1812', '#0b0709'], 'gardens': ['#04100f', '#0d2a26', '#030807'], 'nave': ['#04060f', '#0c1630', '#020309'], 'spire': ['#0c0814', '#2a1a3c', '#07050b'], 'hearth': ['#0c0606', '#2a0e08', '#050202']}
for area, b in bgs.items():
    if area in scenes: continue
    L = []
    for lay in b['layers']:
        if lay['id'] == 'far':
            L.append({'img': f'bg_{area}_far', 'src': lay['img'], 'p': 0.08, 'h': 1.12})
            L.append({'kind': 'rays', 'color': FOG[area], 'a': 0.05, 'count': 4, 'p': 0.15})
            L.append({'kind': 'fog', 'color': FOG[area], 'a': 0.16, 'p': 0.15, 'speed': 9, 'y': 0.45, 'h': 0.6})
        else:
            L.append({'img': f'bg_{area}_{lay["id"]}', 'src': lay['img'], 'p': 0.35, 'h': 1.0, 'tile': True})
            L.append({'kind': 'fog', 'color': FOG[area], 'a': 0.12, 'p': 0.5, 'speed': 18, 'y': 0.62, 'h': 0.45, 'seed': 'b'})
    scenes[area] = {'sky': SKY[area], 'layers': L}
# the painted foreground frame is retired (scenery.js no longer draws it) and the old 3D backdrops are superseded
for sc in scenes.values(): sc['layers'] = [l for l in sc['layers'] if not l.get('front')]
bgs = {a: b for a, b in bgs.items() if a not in scenes}
rigs = {}
p = os.path.join(ROOT, 'assets/rigs')
for f in sorted(glob.glob(os.path.join(p, '*.json'))):
    rigs[os.path.basename(f)[:-5]] = json.load(open(f))
with open(os.path.join(ROOT, 'js/data.js'), 'w') as f:
    f.write('// generated by tools/build_data.py\n')
    f.write('window.WORLD=' + json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ';\n')
    f.write('window.ATLAS=' + json.dumps(atlases, separators=(',', ':')) + ';\n')
    f.write('window.ROOMART=' + json.dumps(art, separators=(',', ':')) + ';\n')
    f.write('window.PROPS=' + json.dumps(props, separators=(',', ':')) + ';\n')
    f.write('window.BGS=' + json.dumps(bgs, separators=(',', ':')) + ';\n')
    f.write('window.SCENES=' + json.dumps(scenes, separators=(',', ':')) + ';\n')
    f.write('window.RIGS=' + json.dumps(rigs, separators=(',', ':')) + ';\n')
print('data.js', os.path.getsize(os.path.join(ROOT, 'js/data.js')) // 1024, 'KB')
